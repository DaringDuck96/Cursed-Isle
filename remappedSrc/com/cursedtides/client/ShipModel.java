package com.cursedtides.client;

import com.cursedtides.entity.ShipEntity;
import com.mojang.blaze3d.vertex.PoseStack;
import com.mojang.blaze3d.vertex.VertexConsumer;
import net.minecraft.client.model.EntityModel;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;

/**
 * Single-masted ship built from boxes. Generated by make_ship.py together with the
 * textures, so the UV layout always matches. Bigger classes render it scaled up.
 */
public class ShipModel extends EntityModel<ShipEntity> {
    private final ModelPart root;
    private final ModelPart sail;
    private final ModelPart mast;
    private final ModelPart yard;
    private final ModelPart flag;
    private final ModelPart emblem;

    public ShipModel(ModelPart root) {
        this.root = root;
        this.sail = root.getChild("sail");
        this.mast = root.getChild("mast");
        this.yard = root.getChild("yard");
        this.flag = root.getChild("flag");
        this.emblem = root.getChild("emblem");
        this.emblem.visible = false;
    }

    /** A flag design painted large across the mainsail, drawn with that flag's texture. */
    public void renderEmblem(PoseStack matrices, VertexConsumer vertices, int light, int overlay) {
        if (!this.sail.visible || this.sail.yScale < 1.0f) return;
        this.emblem.visible = true;
        this.emblem.yScale = 3.4f;
        this.emblem.zScale = 2.2f;
        this.emblem.render(matrices, vertices, light, overlay, 0xFFFFFFFF);
        this.emblem.visible = false;
    }

    /** Hide the painted pennant while a custom flag is drawn in its place. */
    public void setCustomFlag(boolean custom) {
        this.flag.visible = !custom;
    }

    /** An extra mast with its yard and canvas, for two- and three-masted ships. */
    public void renderRig(PoseStack matrices, VertexConsumer vertices, int light, int overlay, int sailColor) {
        this.mast.render(matrices, vertices, light, overlay, 0xFFFFFFFF);
        this.yard.render(matrices, vertices, light, overlay, 0xFFFFFFFF);
        if (this.sail.visible) this.sail.render(matrices, vertices, light, overlay, sailColor);
    }

    /** Just the flag box, drawn with a flag texture laid out on the same UVs. */
    public void renderFlag(PoseStack matrices, VertexConsumer vertices, int light, int overlay) {
        boolean was = this.flag.visible;
        this.flag.visible = true;
        this.flag.render(matrices, vertices, light, overlay, 0xFFFFFFFF);
        this.flag.visible = was;
    }

    public static LayerDefinition getTexturedModelData() {
        MeshDefinition data = new MeshDefinition();
        PartDefinition root = data.getRoot();
        root.addOrReplaceChild("keel", CubeListBuilder.create().texOffs(0, 0).addBox(-10f, 0f, -26f, 20f, 3f, 52f), PartPose.ZERO);
        root.addOrReplaceChild("side_left", CubeListBuilder.create().texOffs(144, 0).addBox(-12f, -10f, -26f, 2f, 13f, 52f), PartPose.ZERO);
        root.addOrReplaceChild("side_right", CubeListBuilder.create().texOffs(0, 65).addBox(10f, -10f, -26f, 2f, 13f, 52f), PartPose.ZERO);
        root.addOrReplaceChild("stern", CubeListBuilder.create().texOffs(108, 65).addBox(-12f, -10f, -28f, 24f, 13f, 2f), PartPose.ZERO);
        root.addOrReplaceChild("bow", CubeListBuilder.create().texOffs(160, 65).addBox(-8f, -10f, 26f, 16f, 13f, 6f), PartPose.ZERO);
        root.addOrReplaceChild("bow_tip", CubeListBuilder.create().texOffs(204, 65).addBox(-4f, -9f, 32f, 8f, 11f, 5f), PartPose.ZERO);
        root.addOrReplaceChild("deck", CubeListBuilder.create().texOffs(0, 130).addBox(-10f, -4f, -26f, 20f, 1f, 52f), PartPose.ZERO);
        root.addOrReplaceChild("rail_left", CubeListBuilder.create().texOffs(144, 130).addBox(-12f, -12f, -26f, 2f, 2f, 52f), PartPose.ZERO);
        root.addOrReplaceChild("rail_right", CubeListBuilder.create().texOffs(0, 184).addBox(10f, -12f, -26f, 2f, 2f, 52f), PartPose.ZERO);
        root.addOrReplaceChild("cabin", CubeListBuilder.create().texOffs(108, 184).addBox(-9f, -12f, -26f, 18f, 8f, 10f), PartPose.ZERO);
        root.addOrReplaceChild("cabin_roof", CubeListBuilder.create().texOffs(164, 184).addBox(-10f, -13f, -27f, 20f, 1f, 12f), PartPose.ZERO);
        root.addOrReplaceChild("mast", CubeListBuilder.create().texOffs(228, 184).addBox(-1f, -80f, 4f, 2f, 76f, 2f), PartPose.ZERO);
        root.addOrReplaceChild("yard", CubeListBuilder.create().texOffs(0, 262).addBox(-20f, -68f, 3f, 40f, 2f, 2f), PartPose.ZERO);
        root.addOrReplaceChild("bowsprit", CubeListBuilder.create().texOffs(84, 262).addBox(-1f, -12f, 36f, 2f, 2f, 16f), PartPose.ZERO);
        root.addOrReplaceChild("flag", CubeListBuilder.create().texOffs(120, 262).addBox(0f, -80f, -6f, 1f, 6f, 10f), PartPose.ZERO);
        root.addOrReplaceChild("emblem", CubeListBuilder.create().texOffs(120, 262).addBox(0f, 0f, -5f, 1f, 6f, 10f),
                PartPose.offsetAndRotation(0f, -57f, 7.6f, 0f, (float) (Math.PI / 2), 0f));
        root.addOrReplaceChild("cannon_l1", CubeListBuilder.create().texOffs(142, 262).addBox(-14f, -8f, -10f, 2f, 2f, 4f), PartPose.ZERO);
        root.addOrReplaceChild("cannon_l2", CubeListBuilder.create().texOffs(154, 262).addBox(-14f, -8f, 8f, 2f, 2f, 4f), PartPose.ZERO);
        root.addOrReplaceChild("cannon_r1", CubeListBuilder.create().texOffs(166, 262).addBox(12f, -8f, -10f, 2f, 2f, 4f), PartPose.ZERO);
        root.addOrReplaceChild("cannon_r2", CubeListBuilder.create().texOffs(178, 262).addBox(12f, -8f, 8f, 2f, 2f, 4f), PartPose.ZERO);
        root.addOrReplaceChild("sail", CubeListBuilder.create().texOffs(0, 280).addBox(-18f, 0f, 6f, 36f, 40f, 1f).texOffs(74, 280).addBox(0f, 16f, 14f, 1f, 36f, 20f), PartPose.offset(0.0f, -66.0f, 0.0f));
        return LayerDefinition.create(data, 256, 512);
    }

    @Override
    public void setAngles(ShipEntity ship, float limbAngle, float limbDistance, float animationProgress,
                          float headYaw, float headPitch) {
        int setting = ship.getSail();
        this.sail.visible = setting > 0;
        this.sail.yScale = setting == 1 ? 0.5f : 1.0f;
        // A little belly in the canvas when the wind is behind her
        this.sail.xRot = setting > 0 ? -0.06f : 0.0f;
    }

    @Override
    public void renderToBuffer(PoseStack matrices, VertexConsumer vertices, int light, int overlay, int color) {
        this.root.render(matrices, vertices, light, overlay, color);
    }

    /** Everything but the canvas, in natural colours. */
    public void renderHull(PoseStack matrices, VertexConsumer vertices, int light, int overlay) {
        boolean wasVisible = this.sail.visible;
        this.sail.visible = false;
        this.root.render(matrices, vertices, light, overlay, 0xFFFFFFFF);
        this.sail.visible = wasVisible;
    }

    /** Just the canvas, tinted (0xAARRGGBB). */
    public void renderSail(PoseStack matrices, VertexConsumer vertices, int light, int overlay, int color) {
        if (this.sail.visible) {
            this.sail.render(matrices, vertices, light, overlay, color);
        }
    }
}
